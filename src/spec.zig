const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;
const Environ = std.process.Environ;
const testing = std.testing;
const types = @import("types.zig");
const Config = @import("config.zig").Config;
const exe = @import("exe.zig");

pub const Overrides = std.StringArrayHashMapUnmanaged([]const u8);

pub fn varsOverlay(arena: Allocator, config: Config) ![]const u8 {
    return std.fmt.allocPrint(arena,
        \\# Auto-generated by orchd — built-in variable declarations
        \\ARG ORCH_DATA={s}
        \\ARG ORCH_PROJECT={s}
        \\ARG ORCH_STATE_DIR={s}
        \\ARG ORCH_CONTAINERS_DIR={s}
        \\
    , .{ config.data_dir, config.project_dir, config.state_dir, config.project_dir });
}

pub fn overrides(arena: Allocator, environ: *const Environ.Map, config: Config, log: *Io.Writer) !Overrides {
    var out: Overrides = .empty;
    var it = environ.iterator();
    while (it.next()) |entry| {
        const key = entry.key_ptr.*;
        if (!std.mem.startsWith(u8, key, "ORCH_ARG_") or key.len == "ORCH_ARG_".len) continue;
        try out.put(arena, key["ORCH_ARG_".len..], entry.value_ptr.*);
    }
    for (config.args) |arg| {
        const eq = std.mem.indexOfScalar(u8, arg, '=') orelse {
            if (config.verbose) try log.print("warning: ignoring --arg '{s}' (expected name=value)\n", .{arg});
            continue;
        };
        try out.put(arena, arg[0..eq], arg[eq + 1 ..]);
    }
    return out;
}

pub fn parse(
    arena: Allocator,
    io: Io,
    environ: *const Environ.Map,
    config: Config,
    log: *Io.Writer,
    diag: *types.Diagnostic,
) !types.Spec {
    const cwd = Io.Dir.cwd();
    try cwd.createDirPath(io, config.state_dir);
    const vars_path = try std.fs.path.join(arena, &.{ config.state_dir, "orchd-vars.orch" });
    try cwd.writeFile(io, .{ .sub_path = vars_path, .data = try varsOverlay(arena, config) });

    const orch = try exe.find(arena, io, "orch", exe.selfDir(arena, io), environ.get("PATH") orelse "") orelse {
        diag.set(arena, "orch not found beside orchd or on PATH", .{});
        return error.OrchNotFound;
    };
    const args = try overrides(arena, environ, config, log);

    var argv: std.ArrayList([]const u8) = .empty;
    try argv.appendSlice(arena, &.{ orch, "parse", vars_path, config.orchfile });
    try argv.appendSlice(arena, config.overlays);
    for (args.keys(), args.values()) |key, value| {
        try argv.appendSlice(arena, &.{ "--arg", try std.fmt.allocPrint(arena, "{s}={s}", .{ key, value }) });
    }

    const result = std.process.run(arena, io, .{ .argv = argv.items }) catch |err| {
        diag.set(arena, "orch parse could not run: {t}", .{err});
        return error.OrchParse;
    };
    if (!result.term.success()) {
        const said = std.mem.trim(u8, result.stderr, " \t\r\n");
        diag.set(arena, "{s}", .{if (std.mem.startsWith(u8, said, "error: ")) said["error: ".len..] else said});
        return error.OrchParse;
    }
    const spec = types.parseSpec(arena, result.stdout) catch |err| {
        diag.set(arena, "orch parse printed a spec orchd cannot read: {t}", .{err});
        return error.OrchParse;
    };

    var unknown: std.ArrayList([]const u8) = .empty;
    for (args.keys()) |key| {
        if (!spec.args.map.contains(key)) try unknown.append(arena, key);
    }
    std.mem.sort([]const u8, unknown.items, {}, lessThan);
    for (unknown.items) |key| {
        try log.print("warning: no ARG named '{s}' is declared; the override is ignored\n", .{key});
    }
    return spec;
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

test "the vars overlay declares where data, project and state live" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    var config = @import("config.zig").forTest("/s");
    config.data_dir = "/srv/data";
    config.project_dir = "/srv/project";
    const vars = try varsOverlay(arena.allocator(), config);
    try testing.expect(std.mem.indexOf(u8, vars, "ARG ORCH_DATA=/srv/data\n") != null);
    try testing.expect(std.mem.indexOf(u8, vars, "ARG ORCH_PROJECT=/srv/project\n") != null);
    try testing.expect(std.mem.indexOf(u8, vars, "ARG ORCH_STATE_DIR=/s\n") != null);
    try testing.expect(std.mem.indexOf(u8, vars, "ARG ORCH_CONTAINERS_DIR=/srv/project\n") != null);
}

test "ARG overrides come from ORCH_ARG_ env, then --arg, which wins" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var environ: Environ.Map = .init(a);
    try environ.put("ORCH_ARG_PORT", "8080");
    try environ.put("ORCH_ARG_HOST", "env");
    try environ.put("ORCH_ARG_", "ignored-no-name");
    try environ.put("PATH", "/bin");
    var config = @import("config.zig").forTest("/s");
    config.args = &.{ "HOST=cli", "malformed" };
    var sink: Io.Writer.Discarding = .init(&.{});
    const got = try overrides(a, &environ, config, &sink.writer);
    try testing.expectEqualStrings("8080", got.get("PORT").?);
    try testing.expectEqualStrings("cli", got.get("HOST").?);
    try testing.expectEqual(2, got.count());
}
